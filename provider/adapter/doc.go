// Package adapter 是协议实现的共用件：写一个协议客户端需要、又与具体协议无关的东西。
//
// 流式响应的分帧、工具调用参数的中立词汇、结果回灌给模型的文本、协议侧错误的形状——
// 这些在每一家协议里都一样或几乎一样，因此下沉到这里，协议包之间不必互相复制，
// 也不必互相引用（互相引用会构成导入循环，编译期即失败）。
//
// 它刻意**不含装配概念**：没有工厂类型、没有注册表、没有"协议叫什么名字"的知识。
// 装配是组装层的事——哪个配置值对应哪种协议、针对已知厂商怎么连线，都在那里决定。
// 因此协议包可以被任何一方独立复用：它们的入口是普通构造函数，只接受已经解析好的
// 连接事实，既不依赖配置模型，也不关心自己被谁选用。
